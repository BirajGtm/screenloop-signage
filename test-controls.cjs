const vm=require('node:vm'),fs=require('node:fs'),assert=require('node:assert/strict');
let data={},handler,now=100000,fullscreen=false;
const hook={addListener(){}},alarms=new Map(),shots=[];
const chrome={runtime:{getURL:p=>'chrome-extension://test/'+p,onMessage:{addListener:f=>handler=f},onStartup:hook},storage:{local:{get:async()=>({})},session:{get:async()=>data,set:async v=>{data=v}}},action:{setBadgeText:async()=>{}},alarms:{clear:async n=>alarms.delete(n),create:async(n,v)=>alarms.set(n,v),onAlarm:hook},tabs:{get:async id=>({id,windowId:7}),update:async()=>{},sendMessage:async(id,m)=>shots.push(m.info),onRemoved:hook,onUpdated:hook},windows:{create:async()=>({id:7,tabs:[{id:1},{id:2},{id:3}]}),update:async(id,v)=>{if(v.state)fullscreen=v.state==='fullscreen'},get:async()=>({state:fullscreen?'fullscreen':'normal'})}};
chrome.storage.session.set=async v=>Object.assign(data,v);
chrome.tabs.onActivated=hook;
const context={chrome,console,URL,Date:{now:()=>now},importScripts(){}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(__dirname+'/chrome-extension/site-access.js','utf8'),context);
vm.runInContext(fs.readFileSync(__dirname+'/chrome-extension/background.js','utf8'),context);
const send=(m,id)=>new Promise(resolve=>handler(m,id?{tab:{id}}:{},resolve));
(async()=>{
  const origins=vm.runInContext("overlayOrigins(['http://google.com/','https://youtube.com/','http://192.168.1.1/'])",context);
  assert.ok(origins.includes('https://www.google.com/*'));
  assert.ok(origins.includes('https://www.youtube.com/*'));
  assert.ok(origins.includes('http://192.168.1.1/*'));
  assert.ok(!origins.some(x=>x.includes('*.')));
  assert.equal((await send({action:'demo'})).ok,true);
  now+=10000;
  assert.equal((await send({action:'overlayControl',control:'pause'},2)).ok,false);
  await send({action:'overlayControl',control:'pause'},1);
  assert.equal(data.player.remaining,20000);assert.equal(data.player.running,false);assert.equal(alarms.size,0);
  assert.equal(shots.at(-1).visible,true);
  now+=60000;
  await send({action:'overlayControl',control:'resume'},1);
  assert.equal(data.player.deadline,now+20000);
  await send({action:'overlayControl',control:'previous'},1);
  assert.equal(data.player.index,2);assert.equal(data.player.deadline,now+30000);
  await send({action:'overlayControl',control:'fullscreen'},3);assert.equal(fullscreen,true);
  await send({action:'overlayControl',control:'fullscreen'},3);assert.equal(fullscreen,false);
  chrome.tabs.sendMessage=async()=>{throw Error('Missing host permission');};
  const denied=await send({action:'visuals'});assert.equal(denied.ok,false);assert.match(denied.error,/Enable site access/);
  assert.equal(data.player.running,true);
  chrome.tabs.sendMessage=async()=>{};
  assert.equal((await send({action:'visuals'})).ok,true);
  assert.equal(Object.keys(data.overlayErrors).length,0);
  console.log('PASS: active-tab authorization, pause freeze, resume remaining duration, previous wrap, fullscreen toggle');
})().catch(e=>{console.error(e);process.exitCode=1});
